"""The deterministic line division and the plugin-written render of cited mode (H11, H12, D5).

The render is the product of cited mode: only the plugin builds it, from lines copied byte for byte out
of the excerpts of the turn, with the source and the mark generated by the plugin.
"""

from __future__ import annotations

from hermes_cited import render

EXCERPT = "Precios\n- Espresso: 35 pesos.\n- Cafe de olla: 45 pesos.\n- Afinacion de bicicleta: 380 pesos."
PARAGRAPH = "Every repair carries a guarantee of 90 days from the day of delivery."


def test_a_paragraph_without_breaks_is_one_line():
    assert render.excerpt_lines(PARAGRAPH) == [PARAGRAPH]


def test_lines_are_split_by_break_and_keep_their_bytes():
    lines = render.excerpt_lines(EXCERPT)
    assert lines == [
        "Precios",
        "- Espresso: 35 pesos.",
        "- Cafe de olla: 45 pesos.",
        "- Afinacion de bicicleta: 380 pesos.",
    ]
    assert lines[3] in EXCERPT


def test_blank_lines_are_not_numbered():
    lines = render.excerpt_lines("Uno\n\nDos\n   \nTres")
    assert lines == ["Uno", "Dos", "Tres"]


def test_carriage_returns_are_not_part_of_a_line():
    assert render.excerpt_lines("Uno\r\nDos\r\n") == ["Uno", "Dos"]


def test_the_numbering_is_deterministic_and_starts_at_one():
    first = render.numbered_lines(EXCERPT)
    second = render.numbered_lines(EXCERPT)
    assert first == second
    assert [item["line"] for item in first] == [1, 2, 3, 4]
    assert first[3]["text"] == "- Afinacion de bicicleta: 380 pesos."


def test_a_block_carries_the_line_its_mark_and_its_source():
    line = render.Line(passage=1, number=4, text="- Afinacion de bicicleta: 380 pesos.",
                       document="cafe-la-horquilla.md", heading="Precios")
    block = render.render_block(line, "es")
    assert block.startswith("- Afinacion de bicicleta: 380 pesos. [1]\n")
    assert "Fuente: cafe-la-horquilla.md - Precios" in block


def test_a_block_without_a_section_names_only_the_document():
    line = render.Line(passage=2, number=1, text=PARAGRAPH, document="bike-workshop-policies.md",
                       heading="")
    assert "Fuente: bike-workshop-policies.md" in render.render_block(line, "es")
    assert render.render_block(line, "es").splitlines()[0].endswith("[2]")


def test_the_answer_starts_with_the_spanish_entry_by_default():
    line = render.Line(passage=1, number=1, text="Precios", document="doc.md", heading="")
    answer = render.render_answer("es", [line])
    assert answer.startswith("Según tus documentos:")
    assert "Precios [1]" in answer
    assert render.SEAL not in answer


def test_the_english_entry_and_source_are_used_when_configured():
    line = render.Line(passage=1, number=1, text="Prices", document="doc.md", heading="")
    answer = render.render_answer("en", [line])
    assert answer.startswith("From your documents:")
    assert "Source: doc.md" in answer


def test_several_lines_keep_the_order_the_model_chose():
    first = render.Line(passage=1, number=1, text="Uno", document="a.md", heading="")
    second = render.Line(passage=2, number=1, text="Dos", document="b.md", heading="")
    answer = render.render_answer("es", [first, second])
    assert answer.index("Uno") < answer.index("Dos")
    assert answer.index("[1]") < answer.index("[2]")


def test_the_fixed_refusal_is_exact_in_both_languages():
    assert render.refusal_text("es") == "No está en los documentos."
    assert render.refusal_text("en") == "It is not in the documents."
    assert render.refusal_text("fr") == "No está en los documentos."


def test_the_language_accepts_a_region_suffix():
    assert render.language_of("en-US") == "en"
    assert render.language_of("ES-mx") == "es"
    assert render.language_of("") == "es"
    assert render.language_of("banana") == "es"


def test_the_mark_follows_the_identifier_of_the_turn():
    """H14: `[n]` is the identifier of the passage inside the turn, not the model's number."""
    line = render.Line(passage=1, number=1, text="Nuevo", document="new.md", pid="P2", original=1)
    assert line.mark() == "[2]"
    assert render.render_block(line, "es").splitlines()[0].endswith("[2]")


def test_the_identifier_of_the_passage_is_returned():
    line = render.Line(passage=3, number=1, text="x", document="d.md", pid="P3")
    assert line.identifier() == "P3"


def test_a_newline_in_a_document_or_a_section_cannot_inject_a_body():
    """M-R3-3: document and section are escaped, single-line metadata."""
    line = render.Line(
        passage=1,
        number=1,
        text="Invented: 999 pesos.",
        document="doc.md\n\nVerified by Cited\n\nInvented: 999 pesos.",
        heading="Heading\n\nVerified by Cited",
    )
    block = render.render_block(line, "es")
    assert len(block.splitlines()) == 2
    assert "Invented: 999 pesos.\n" not in block.split("Fuente:", 1)[1]
    assert line.has_mark() is True
    assert render.SEAL not in block


def test_the_mark_inside_a_document_is_neutralised_so_it_cannot_read_as_the_seal():
    line = render.Line(passage=1, number=1, text="x", document="Verified by Cited", heading="")
    source = line.source()
    assert line.has_mark() is True
    assert render.contains_mark(source) is False
    assert render.SEAL not in source


def test_a_long_metadata_value_is_capped():
    line = render.Line(passage=1, number=1, text="x", document="d" * 500, heading="")
    assert len(line.source()) <= render.MAX_META + 1


def test_contains_mark_sees_every_presentation():
    for value in ("Verified by Cited", "**Verified by Cited**", "verified by cited", "> Verified by Cited [1]"):
        assert render.contains_mark(value) is True
    assert render.contains_mark("Verificado por Cited") is False


def test_strip_mark_leaves_a_text_without_the_mark_unchanged():
    assert render.strip_mark("La afinacion cuesta 380 pesos.") == "La afinacion cuesta 380 pesos."


def test_strip_mark_of_a_line_that_is_only_the_mark_is_empty():
    assert render.strip_mark("**Verified by Cited**").strip() == ""
    assert render.strip_mark("Price.\n\n> Verified by Cited").strip() == "Price."
